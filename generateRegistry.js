// generateRegistry.js
// Run from WEB.300: node .\generateRegistry.js
// Scans photographs directly inside Collections/. It ignores .txt files and subfolders.
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = __dirname;
const COLLECTIONS = path.join(ROOT, 'Collections');
const REGISTRY = path.join(ROOT, 'registry.js');
const IMAGE_EXT = /\.(jpg|jpeg|png|gif|webp)$/i;

function naturalCompare(a, b) {
    return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
}

function readExistingRegistry() {
    if (!fs.existsSync(REGISTRY)) {
        return { paths: [], titles: {}, descriptions: {} };
    }

    const source = fs.readFileSync(REGISTRY, 'utf8');
    try {
        const data = vm.runInNewContext(
            source + '\n;({ paths: MASTER_IMAGE_REGISTRY || [], titles: IMAGE_TITLES || {}, descriptions: IMAGE_DESCRIPTIONS || {}, icons: GALLERY_ICON_PATHS || {}, fileMetadata: IMAGE_FILE_METADATA || {} })',
            Object.create(null),
            { timeout: 1000 }
        );
        return {
            paths: Array.isArray(data.paths) ? data.paths : [],
            titles: data.titles && typeof data.titles === 'object' ? data.titles : {},
            descriptions: data.descriptions && typeof data.descriptions === 'object' ? data.descriptions : {},
            icons: data.icons && typeof data.icons === 'object' ? data.icons : null,
            fileMetadata: data.fileMetadata && typeof data.fileMetadata === 'object' ? data.fileMetadata : {}
        };
    } catch (error) {
        throw new Error('Could not safely read existing title/description data from registry.js. Nothing was changed. ' + error.message);
    }
}

if (!fs.existsSync(COLLECTIONS) || !fs.statSync(COLLECTIONS).isDirectory()) {
    throw new Error('Collections folder not found: ' + COLLECTIONS + '. Nothing was changed.');
}

const existing = readExistingRegistry();
const files = fs.readdirSync(COLLECTIONS, { withFileTypes: true })
    .filter(entry => entry.isFile() && IMAGE_EXT.test(entry.name))
    .map(entry => entry.name);

if (files.length === 0) {
    throw new Error('No photographs found directly inside Collections/. registry.js was not overwritten.');
}

// Preserve every surviving registry entry in its existing position.
// Newly discovered photographs are appended in natural filename order.
const actualByLowerName = new Map(files.map(file => [file.toLowerCase(), file]));
const used = new Set();
const preservedPaths = [];
existing.paths.forEach(function(oldPath) {
    const normalized = String(oldPath).replace(/\\\\/g, '/');
    const parts = normalized.split('/');
    if (parts.length !== 2 || parts[0].toLowerCase() !== 'collections') return;
    const actualName = actualByLowerName.get(parts[1].toLowerCase());
    if (!actualName || used.has(actualName.toLowerCase())) return;
    used.add(actualName.toLowerCase());
    preservedPaths.push('Collections/' + actualName);
});
const newFiles = files.filter(file => !used.has(file.toLowerCase())).sort(naturalCompare);
const imagePaths = preservedPaths.concat(newFiles.map(file => 'Collections/' + file));
const iconPaths = existing.icons || {
    magnifier: 'assets/magnifier-icon.png',
    dark: 'assets/dark-icon.png',
    light: 'assets/light-icon.png'
};

const output = [
    '// Generated by generateRegistry.js from photographs directly inside Collections/.',
    'const GALLERY_ASSET_ROOT = "Collections";',
    'const GALLERY_ICON_PATHS = ' + JSON.stringify(iconPaths, null, 4) + ';',
    'const MASTER_IMAGE_REGISTRY = ' + JSON.stringify(imagePaths, null, 4) + ';',
    'const IMAGE_TITLES = ' + JSON.stringify(existing.titles, null, 4) + ';',
    'const IMAGE_DESCRIPTIONS = ' + JSON.stringify(existing.descriptions, null, 4) + ';',
    'const IMAGE_FILE_METADATA = ' + JSON.stringify(existing.fileMetadata, null, 4) + ';',
    'function getImageTitle(path) {',
    "    const key = String(path).replace(/\\\\/g, '/');",
    "    return key.split('/').pop().replace(/\\.[^/.]+$/, '');",
    '}',
    'function getImageDescription(path) {',
    "    const key = String(path).replace(/\\\\/g, '/');",
    "    return IMAGE_DESCRIPTIONS[key] || '';",
    '}',
    ''
].join('\n');

const temp = REGISTRY + '.tmp';
fs.writeFileSync(temp, output, 'utf8');
fs.renameSync(temp, REGISTRY);

console.log('registry.js updated: ' + imagePaths.length + ' photographs found directly inside Collections/.');
console.log('Preserved ' + Object.keys(existing.titles).length + ' title entries and ' +
    Object.keys(existing.descriptions).length + ' description entries.');
